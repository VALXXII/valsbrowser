"""R45: generates src/annotation-font.h — the bundled Inter Display (assets/fonts), subset to the label characters, as base64
for the page script (annotation-script.h loads it as a FontFace from an ArrayBuffer: no request, no CSP, nothing installed).

    pip install --target <dir> fonttools ; PYTHONPATH=<dir> python tests/annotations-ui/make_label_font.py

The labels (element name, size, « En attente », value labels) then use the same font file as the native copy of the frame
(annotation-frame.h, Ink's bundled Inter Display) and as Paper, whatever is installed on the machine.
"""
import base64, io, os
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
UNICODES = "U+0020-007E,U+00A0-00FF,U+0152-0153,U+2013-2014,U+2018-201E,U+2026,U+2039-203A,U+2212"
out = {}
for weight, name in (("400", "Regular"), ("500", "Medium")):
    opts = subset.Options(); opts.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]; opts.hinting = True
    font = TTFont(os.path.join(ROOT, "assets", "fonts", f"InterDisplay-{name}.ttf"))
    s = subset.Subsetter(opts); s.populate(unicodes=subset.parse_unicodes(UNICODES)); s.subset(font)
    buf = io.BytesIO(); font.save(buf); out[name] = base64.b64encode(buf.getvalue()).decode()

def chunks(s, n=4000):   # several literals: no compiler limit on one string literal
    return "\n".join('    "' + s[i:i + n] + '"' for i in range(0, len(s), n))

with open(os.path.join(ROOT, "src", "annotation-font.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n// GENERATED by tests/annotations-ui/make_label_font.py — do not edit. R45: the bundled Inter Display (assets/fonts,\n"
            "// OFL, Inter-LICENSE.txt), subset to " + UNICODES + ", base64. Loaded by the page script as a FontFace\n"
            "// (« Browser Annotation Inter ») so the labels in the page use the very font the native copy draws with.\n"
            "namespace NativeChrome { namespace Annotations {\n")
    for name in ("Regular", "Medium"):
        f.write(f"inline const char* LabelFont{name}() {{\n    return\n{chunks(out[name])};\n}}\n")
    f.write("}} // namespace NativeChrome::Annotations\n")
print({k: len(v) for k, v in out.items()})
